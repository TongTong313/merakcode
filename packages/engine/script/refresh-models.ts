/**
 * Refreshes the engine's bundled models.dev catalog snapshot `src/provider/models-snapshot.ts` (run before a release).
 *
 * Machines that cannot reach models.dev (intranet, offline) get the model catalog from this snapshot.
 *
 * Sources, in priority order: the local file at MODELS_DEV_API_JSON → MERAKCODE_MODELS_URL (intranet mirror) →
 * https://models.dev. If none is reachable, the old snapshot is kept and the script exits non-zero so the release
 * owner notices.
 */
import path from "node:path"
import { Filesystem } from "@merakcode/util/filesystem"

const target = path.resolve(import.meta.dirname, "../src/provider/models-snapshot.ts")
const url = `${process.env.MERAKCODE_MODELS_URL || "https://models.dev"}/api.json`

const data = process.env.MODELS_DEV_API_JSON
  ? await Filesystem.readText(process.env.MODELS_DEV_API_JSON)
  : await fetch(url, { signal: AbortSignal.timeout(30_000) })
      .then((response) => (response.ok ? response.text() : undefined))
      .catch(() => undefined)

if (!data) {
  console.error(`failed to fetch model catalog (${process.env.MODELS_DEV_API_JSON ?? url}), keeping old snapshot`)
  process.exit(1)
}
// Parse first: only valid JSON may enter the source tree; failing is better than shipping bad data
const providers = Object.keys(JSON.parse(data)).length
await Filesystem.write(
  target,
  `// Auto-generated by refresh-models.ts - do not edit\nexport const snapshot = ${data} as const\n`,
)
console.log(`refreshed models-snapshot.ts: ${providers} providers`)
