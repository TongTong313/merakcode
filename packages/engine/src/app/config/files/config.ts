  /**
   * Removes a provider entry from the config file of a scope; update* (mergeDeep) can only add.
   * - Real delete (clearReferences=true, the default): also removes model references to the provider.
   * - Delete-then-write during an edit (clearReferences=false): only removes the provider subtree and keeps
   *   references that are still valid, so one edit does not wipe config.model / agent.*.model.
   */
  export async function deleteProvider(
    providerID: string,
    scope: "project" | "global",
    options?: { clearReferences?: boolean },
  ) {
    const filepath = scope === "global" ? globalConfigFile() : projectMerakCodeFile()
    await commitConfigTextEdit(filepath, scope, (text) => {
      const before = parseConfigObject(text)
      const after = structuredClone(before) as Record<string, unknown>
      if (options?.clearReferences !== false) clearStaleModelRefs(after, providerID)
      const provider = after["provider"]
      if (provider && typeof provider === "object" && !Array.isArray(provider)) {
        delete (provider as Record<string, unknown>)[providerID]
      }
      return patchConfigTopLevelKeys(text, before, after)
    })
  }

