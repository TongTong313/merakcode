  async function loadState(warnings: ConfigWarning[]) {
    const auth = await Auth.all()

    // Config loading order (low -> high precedence):
    // 1) Remote .well-known/merakcode (org defaults)
    // 2) Global config (~/.merakcode/merakcode.json{,c})
    // 3) Custom config (MERAKCODE_CONFIG)
    // 3.5) Workspace config (multi-root: `<data>/workspace/<ws_id>/merakcode.json`, never .code-workspace)
    // 4) Project config (merakcode.json{,c}) — primary only
    // 5) .merakcode directories (.merakcode/agents/, .merakcode/commands/, .merakcode/plugins/, .merakcode/merakcode.json{,c})
    // 6) Inline config (MERAKCODE_CONFIG_CONTENT)
    // Managed config directory is enterprise-only and always overrides everything above.
    let result: Info = {}
    for (const [key, value] of Object.entries(auth)) {
      if (value.type === "wellknown") {
        process.env[value.key] = value.token
        log.debug("fetching remote config", { url: `${key}/.well-known/merakcode` })
        const response = await fetch(`${key}/.well-known/merakcode`)
        if (!response.ok) {
          throw new Error(`failed to fetch remote config from ${key}: ${response.status}`)
        }
        const wellknown = (await response.json()) as any
        const remoteConfig = wellknown.config ?? {}
        // Add $schema to prevent load() from trying to write back to a non-existent file
        if (!remoteConfig.$schema) remoteConfig.$schema = SCHEMA
        result = mergeSources(result, await load(JSON.stringify(remoteConfig), `${key}/.well-known/merakcode`))
        log.debug("loaded remote config from well-known", { url: key })
      }
    }

    // Global user config overrides remote config.
    result = mergeSources(result, await global())
    // global() may already have been warmed up by getGlobal(): merge its cached warnings into this Instance.
    if (cache.globalWarnings.length > 0) warnings.push(...cache.globalWarnings)

    // Custom config path overrides global config.
    if (Flag.MERAKCODE_CONFIG) {
      result = mergeSources(result, await loadFile(Flag.MERAKCODE_CONFIG))
      log.debug("loaded custom config", { path: Flag.MERAKCODE_CONFIG })
    }

    // Workspace layer: above global/custom, below the primary project config. Not used for single-root projects.
    if (Instance.project.kind === "workspace") {
      const wsFile = workspaceMerakCodeFile()
      result = mergeSources(result, await loadFile(wsFile))
      log.debug("loaded workspace config", { path: wsFile })
    }

    // Project config overrides global and remote config.
    // Multi-root: only the primary root (Instance.directory up to worktree) loads the full merge chain. Secondary
    // roots never override permission/agent, so they cannot widen permissions; their AGENTS files are loaded by
    // InstructionPrompt.
    if (!Flag.MERAKCODE_DISABLE_PROJECT_CONFIG) {
      for (const file of ["merakcode.jsonc", "merakcode.json"]) {
        const found = await Filesystem.findUp(file, Instance.directory, Instance.worktree)
        for (const resolved of found.toReversed()) {
          result = mergeSources(result, await loadFile(resolved))
        }
      }
    }

    result.agent = result.agent || {}
    result.mode = result.mode || {}
    result.plugin = result.plugin || []

    // Only scan project .merakcode/ directories when project discovery is enabled
    const scanned = Flag.MERAKCODE_DISABLE_PROJECT_CONFIG
      ? []
      : await Array.fromAsync(
          Filesystem.up({
            targets: [".merakcode"],
            start: Instance.directory,
            // Git projects scan up to the git root (monorepos keep config at the root). Non-git projects
            // (worktree="/") scan only the current directory; walking up would pick up the .merakcode of
            // ancestors such as home and load their skills into this project, breaking project isolation.
            stop: Instance.worktree === "/" ? Instance.directory : Instance.worktree,
          }),
        )
    // The global directory (~/.merakcode) is laid out like a project's .merakcode/. When home is inside the project,
    // the scan finds it again (possibly spelled differently on Windows); it stays global and loads once.
    const directories = unique(
      [Global.Path.config, ...scanned.filter((dir) => !Filesystem.sameDirectory(dir, Global.Path.config))].map(
        sanitizePath,
      ),
    ).filter((dir) => existsSync(dir))

    // .merakcode directory config overrides (project and global) config sources.
    if (Flag.MERAKCODE_CONFIG_DIR) {
      directories.push(Flag.MERAKCODE_CONFIG_DIR)
      log.debug("loading config from MERAKCODE_CONFIG_DIR", { path: Flag.MERAKCODE_CONFIG_DIR })
    }

    const deps = []

    for (const dir of directories) {
      // The global merakcode.json was merged above with global precedence, below the project config
      const globalDir = Filesystem.sameDirectory(dir, Global.Path.config)
      if ((dir.endsWith(".merakcode") && !globalDir) || dir === Flag.MERAKCODE_CONFIG_DIR) {
        for (const file of ["merakcode.jsonc", "merakcode.json"]) {
          log.debug(`loading config from ${path.join(dir, file)}`)
          result = mergeSources(result, await loadFile(path.join(dir, file)))
          // to satisfy the type checker
          result.agent ??= {}
          result.mode ??= {}
          result.plugin ??= []
        }
      }

      deps.push(
        iife(async () => {
          const shouldInstall = await needsInstall(dir)
          if (shouldInstall) await installDependencies(dir)
        }),
      )

      result.command = mergeDeep(result.command ?? {}, await loadCommand(dir))
      result.agent = mergeDeep(result.agent, await loadAgent(dir))
      result.agent = mergeDeep(result.agent, await loadMode(dir))
      result.plugin.push(...(await loadPlugin(dir)))
    }

    // Secondary roots: resource scope only. Commands and skills directories join `directories`;
    // permission/agent/provider/model are never merged.
    if (!Flag.MERAKCODE_DISABLE_PROJECT_CONFIG && Instance.workspace.folders.length > 1) {
      for (const folder of Instance.workspace.folders) {
        if (Filesystem.sameDirectory(folder.path, Instance.directory)) continue
        const dir = sanitizePath(path.join(folder.path, ".merakcode"))
        if (!existsSync(dir)) continue
        result.command = mergeDeep(result.command ?? {}, await loadCommand(dir))
        for (const file of ["merakcode.jsonc", "merakcode.json"]) {
          result = mergeSources(result, pickSecondaryRootConfig(await loadFile(path.join(dir, file))))
        }
        if (!directories.includes(dir)) directories.push(dir)
      }
    }

    // Inline config content overrides all non-managed config sources.
    if (Flag.MERAKCODE_CONFIG_CONTENT) {
      const inline = parseFlagJson(Flag.MERAKCODE_CONFIG_CONTENT, "MERAKCODE_CONFIG_CONTENT")
      if (inline !== undefined) {
        const recovered = recoverConfig(
          Info,
          globalFields(inline, "MERAKCODE_CONFIG_CONTENT", false),
          "MERAKCODE_CONFIG_CONTENT",
        )
        emitWarnings(recovered.warnings)
        // Local plugins go through the same resolver as file config (directory packages resolve to their entry);
        // otherwise they would be installed as npm packages. Inline config has no file to resolve relative paths
        // against, so only absolute paths are resolved; plugin loading reports a clear error for relative ones.
        const data = resolvePlugins(
          recovered.data as Info,
          path.join(Instance.directory, "MERAKCODE_CONFIG_CONTENT"),
          (spec) => path.isAbsolute(spec),
        )
        result = mergeSources(result, data)
        log.debug("loaded custom config from MERAKCODE_CONFIG_CONTENT")
      }
    }

    // Load managed config files last (highest priority) - enterprise admin-controlled
    // Kept separate from directories array to avoid write operations when installing plugins
    // which would fail on system directories requiring elevated permissions
    // This way it only loads config file and not skills/plugins/commands
    if (existsSync(managedConfigDir)) {
      for (const file of ["merakcode.jsonc", "merakcode.json"]) {
        result = mergeSources(result, await loadFile(path.join(managedConfigDir, file)))
      }
    }

    result.agent = AgentSettings.migrateModes(result.agent, result.mode)

    if (Flag.MERAKCODE_PERMISSION) {
      const perms = parseFlagJson(Flag.MERAKCODE_PERMISSION, "MERAKCODE_PERMISSION")
      if (perms) {
        result.permission = mergeDeep(result.permission ?? {}, perms as Permission)
      }
    }

    result.permission = PermissionCompatibility.toolsPermission(result.tools, result.permission)

    // Deprecated permission fields are detected and stripped in load() (see DEPRECATED_SAFETY_FIELDS).

    // Apply flag overrides for compaction settings
    if (Flag.MERAKCODE_DISABLE_AUTOCOMPACT) {
      result.compaction = { ...result.compaction, auto: false }
    }
    if (Flag.MERAKCODE_DISABLE_PRUNE) {
      result.compaction = { ...result.compaction, prune: false }
    }

    result.plugin = deduplicatePlugins(result.plugin ?? [])

    return {
      config: result,
      directories,
      deps,
      warnings,
    }
  }

  export async function waitForDependencies() {
    const deps = await state().then((x) => x.deps)
    // installDependencies already catches its own errors; allSettled makes sure an unexpected rejection still
    // never reaches the plugin/tool loading chain.
    await Promise.allSettled(deps)
  }

  // Local .ts/.js tools import the bare specifier `import { tool } from "@merakcode/sdk/plugin"`. A released engine
  // cannot resolve it from inside itself, and the config directory should not fetch the plugin API from a registry:
  // intranet or offline machines cannot reach it, and the fetched version may not match the engine.
  // So a minimal shim is written under the config directory's node_modules: only ./plugin, where tool() is the
  // identity function and tool.schema is the public zod (installable and cacheable from the registry). A real SDK
  // installed by the user is left alone.
  // The shim's zod and the engine's bundled zod are different instances, but z.object(def.args) only reads the
  // { key: schema } shape, which works across instances.
  const PLUGIN_SHIM_PKG = "@merakcode/sdk"
  // Shim version follows the engine version, so needsInstall rewrites the shim after an upgrade.
  const pluginShimVersion = () => (Installation.isLocal() ? "0.0.0-local" : Installation.VERSION)

  /** The @merakcode/sdk in a config directory: missing, our shim, or a real package installed by the user */
  async function installedSdk(dir: string) {
    const pkg = await Filesystem.readJson(path.join(dir, "node_modules", PLUGIN_SHIM_PKG, "package.json")).catch(
      () => undefined,
    )
    if (!pkg) return undefined
    return pkg.merakcodeShim === true ? { shim: true as const, version: pkg.version } : { shim: false as const }
  }

  /** Writes the minimal shim package to dir/node_modules/@merakcode/sdk so local tools can import it */
  async function writePluginShim(dir: string) {
    if ((await installedSdk(dir))?.shim === false) return
    const shimRoot = path.join(dir, "node_modules", PLUGIN_SHIM_PKG)
    await fs.mkdir(shimRoot, { recursive: true })

    await Filesystem.write(
      path.join(shimRoot, "plugin.js"),
      ['import { z } from "zod"', "export function tool(input) { return input }", "tool.schema = z"].join("\n"),
    )

    await Filesystem.write(
      path.join(shimRoot, "package.json"),
      JSON.stringify(
        {
          name: PLUGIN_SHIM_PKG,
          version: pluginShimVersion(),
          merakcodeShim: true,
          type: "module",
          exports: { "./plugin": "./plugin.js" },
          dependencies: { zod: "*" },
        },
        null,
        2,
      ),
    )
  }

  export async function installDependencies(dir: string) {
    try {
      // The shim is written locally: no network access, and no private package in package.json.
      await writePluginShim(dir)

      // Run an install only when zod cannot be resolved yet; zod is public, so the install can succeed.
      const zodResolved = existsSync(path.join(dir, "node_modules", "zod"))
      if (zodResolved) {
        log.info("dependency.install.skipped", { dir, reason: "zod_available" })
      } else {
        const pkg = path.join(dir, "package.json")
        const json = await Filesystem.readJson(pkg).catch(() => ({}) as Record<string, any>)
        json.dependencies = { ...(json.dependencies ?? {}), zod: json.dependencies?.zod ?? "*" }
        await Filesystem.write(pkg, JSON.stringify(json, null, 2))

        const gitignore = path.join(dir, ".gitignore")
        const hasGitIgnore = await Filesystem.isFile(gitignore)
        if (!hasGitIgnore)
          await Filesystem.write(gitignore, ["node_modules", "package.json", "bun.lock", ".gitignore"].join("\n"))

        // Installs the dependencies declared in package.json (zod and any public packages local plugins use).
        // Failures are logged only: users without local tools are unaffected, and the shim is already in place.
        const started = Date.now()
        const abort = new AbortController()
        let finished = false
        let timedOut = false
        log.info("dependency.install.started", {
          dir,
          reason: "zod_missing",
          timeout: DEPENDENCY_INSTALL_TIMEOUT_MS,
          proxy: proxied(),
        })
        const stalled = setTimeout(() => {
          if (finished) return
          log.warn("dependency.install.stalled", {
            dir,
            duration: Date.now() - started,
            threshold: DEPENDENCY_INSTALL_STALL_MS,
          })
        }, DEPENDENCY_INSTALL_STALL_MS)
        const timeout = setTimeout(() => {
          if (finished) return
          timedOut = true
          log.error("dependency.install.timeout", {
            dir,
            duration: Date.now() - started,
            timeout: DEPENDENCY_INSTALL_TIMEOUT_MS,
          })
          abort.abort()
        }, DEPENDENCY_INSTALL_TIMEOUT_MS)

        await Npm.installDependencies(dir, abort.signal)
          .then(() => {
            if (timedOut) return
            if (!existsSync(path.join(dir, "node_modules", "zod"))) {
              throw new Error("dependency install completed without node_modules/zod")
            }
            log.info("dependency.install.completed", {
              dir,
              duration: Date.now() - started,
            })
          })
          .catch((e) => {
            if (timedOut) return
            log.error("dependency.install.failed", {
              dir,
              duration: Date.now() - started,
              error: e instanceof Error ? e.message : String(e),
            })
          })
          .finally(() => {
            finished = true
            clearTimeout(stalled)
            clearTimeout(timeout)
          })
      }
    } catch (e) {
      // Must never throw: this runs in an iife nobody awaits, so a throw would become an unhandled rejection.
      log.error("dependency.install.failed", {
        dir,
        phase: "prepare",
        error: e instanceof Error ? e.message : String(e),
      })
    }
  }

  async function isWritable(dir: string) {
    try {
      await fs.access(dir, constants.W_OK)
      return true
    } catch {
      return false
    }
  }

  async function needsInstall(dir: string) {
    try {
      // Some config dirs may be read-only.
      // Installing deps there will fail; skip installation in that case.
      const writable = await isWritable(dir)
      if (!writable) {
        log.debug("config dir is not writable, skipping dependency install", { dir })
        return false
      }

      // Install when the shim is missing or from another engine version (first run or after an upgrade).
      // A real SDK installed by the user needs no shim.
      const sdk = await installedSdk(dir)
      if (!sdk) return true
      if (sdk.shim && sdk.version !== pluginShimVersion()) return true

      if (!existsSync(path.join(dir, "node_modules", "zod"))) return true

      log.info("dependency.install.skipped", { dir, reason: "zod_available" })
      return false
    } catch (e) {
      // A failed check must not turn into an install failure or unhandled rejection; skip the install.
      log.warn("needsInstall check failed, skipping install", {
        dir,
        error: e instanceof Error ? e.message : String(e),
      })
      return false
    }
  }

  function rel(item: string, patterns: string[]) {
    const normalized = item.replace(/\\/g, "/")
    for (const pattern of patterns) {
      const index = normalized.indexOf(pattern)
      if (index === -1) continue
      return normalized.slice(index + pattern.length)
    }
  }

  function trim(file: string) {
    const ext = path.extname(file)
    return ext.length ? file.slice(0, -ext.length) : file
  }

  async function configParseErrorObject(input: {
    kind: "command" | "agent" | "mode" | "skill" | "rule"
    path: string
    reason: string
  }) {
    const { Message } = await import("../../../agent/session/message")
    return new Message.ConfigParseError({
      ...input,
      messageKey: "error.configParse",
      params: input,
      message: `Failed to parse ${input.kind} ${input.path}: ${input.reason}`,
    }).toObject()
  }

  const COMMAND_GLOB = new Glob("{command,commands}/**/*.md")
  async function loadCommand(dir: string) {
    const result: Record<string, Command> = {}
    for await (const item of COMMAND_GLOB.scan({
      absolute: true,
      followSymlinks: true,
      dot: true,
      cwd: dir,
    })) {
      const md = await ConfigMarkdown.parse(item).catch(async (err) => {
        const reason = ConfigMarkdown.FrontmatterError.isInstance(err)
          ? err.data.message
          : `Failed to parse command ${item}`
        const { Session } = await import("../../../agent/session")
        Bus.publish(Session.Event.Error, {
          error: await configParseErrorObject({
            kind: "command",
            path: item,
            reason,
          }),
        })
        log.error("failed to load command", { command: item, err })
        return undefined
      })
      if (!md) continue

      const patterns = ["/.merakcode/command/", "/.merakcode/commands/", "/command/", "/commands/"]
      const file = rel(item, patterns) ?? path.basename(item)
      const name = trim(file)

      const config = {
        name,
        ...md.data,
        template: md.content.trim(),
      }
      const parsed = Command.safeParse(config)
      if (parsed.success) {
        result[config.name] = parsed.data
        continue
      }
      emitWarnings(
        parsed.error.issues.map((issue) => ({
          path: item,
          item: issue.path.length ? issue.path.map(String).join(".") : name,
          reason: issue.message || issue.code,
        })),
      )
    }
    return result
  }

  const AGENT_GLOB = new Glob("{agent,agents}/**/*.md")
  async function loadAgent(dir: string) {
    const result: Record<string, Agent> = {}

    for await (const item of AGENT_GLOB.scan({
      absolute: true,
      followSymlinks: true,
      dot: true,
      cwd: dir,
    })) {
      const md = await ConfigMarkdown.parse(item).catch(async (err) => {
        const reason = ConfigMarkdown.FrontmatterError.isInstance(err)
          ? err.data.message
          : `Failed to parse agent ${item}`
        const { Session } = await import("../../../agent/session")
        Bus.publish(Session.Event.Error, {
          error: await configParseErrorObject({
            kind: "agent",
            path: item,
            reason,
          }),
        })
        log.error("failed to load agent", { agent: item, err })
        return undefined
      })
      if (!md) continue

      const patterns = ["/.merakcode/agent/", "/.merakcode/agents/", "/agent/", "/agents/"]
      const file = rel(item, patterns) ?? path.basename(item)
      const agentName = trim(file)

      const config = {
        name: agentName,
        ...md.data,
        prompt: md.content.trim(),
      }
      const parsed = Agent.safeParse(config)
      if (parsed.success) {
        result[config.name] = parsed.data
        continue
      }
      emitWarnings(
        parsed.error.issues.map((issue) => ({
          path: item,
          item: issue.path.length ? issue.path.map(String).join(".") : agentName,
          reason: issue.message || issue.code,
        })),
      )
    }
    return result
  }

