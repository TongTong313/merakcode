  async function loadFile(filepath: string, globalSource = false): Promise<Info> {
    log.info("loading", { path: filepath })
    let text = await Filesystem.readText(filepath).catch((err) => {
      if (err.code === "ENOENT") return
      emitWarnings([
        {
          path: filepath,
          item: "(root)",
          reason: {
            zh: `无法读取配置文件：${err.message ?? err.code ?? "unknown"}；已临时按空配置加载`,
            en: `Cannot read the config file: ${err.message ?? err.code ?? "unknown"}; loaded as empty for now`,
          },
        },
      ])
      return
    })
    if (!text) return {}
    return load(text, filepath, globalSource)
  }

  async function load(text: string, configFilepath: string, globalSource = false) {
    const original = text
    const source = await parseConfigSource(text, configFilepath)
    emitWarnings(source.warnings)
    if (source.invalid) return {} as Info
    const data = source.data

    const deprecated = detectDeprecated(data, DEPRECATED_SAFETY_FIELDS)
    if (deprecated.length > 0) {
      log.warn(`deprecated config fields ignored, see CHANGELOG: ${deprecated.join(", ")}`)
    }

    // Migrate old fields that have an equivalent, then strip the deprecated ones before schema validation.
    const cleaned = globalFields(normalizeDeprecatedForWrite(data), configFilepath, globalSource)

    // Info uses .strip(), so unknown top-level keys do not fail safeParse; they become warnings for the UI.
    // Nothing is written to disk.
    emitUnknownTopLevelKeys(cleaned, configFilepath)

    const parsed = validateConfig(Info, cleaned, configFilepath)
    emitWarnings(parsed.warnings)
    if (parsed.valid && !parsed.data.$schema) {
      parsed.data.$schema = SCHEMA
      await addSchema(configFilepath, original).catch(() => {})
    }
    return resolvePlugins(parsed.data, configFilepath)
  }

  const addSchema = (filepath: string, original: string) => ConfigFile.addSchema(filepath, original, SCHEMA)

  function globalFields(value: unknown, filepath: string, globalSource: boolean) {
    if (!isRecord(value)) return value
    const result = { ...value }
    if (isRecord(result.collaboration) && result.collaboration.products !== undefined) {
      emitWarnings([
        {
          path: filepath,
          item: "collaboration.products",
          reason: {
            zh: "旧产品接入配置已移除，请在全局 agentConnections.products 中配置",
            en: "The old product connection setting was removed; use global agentConnections.products",
          },
        },
      ])
      const collaboration = { ...result.collaboration }
      delete collaboration.products
      result.collaboration = collaboration
    }
    const warn = (item: string) =>
      emitWarnings([
        {
          path: filepath,
          item,
          reason: {
            zh: "智能体接入与角色模板仅支持全局配置，已忽略此来源的设置",
            en: "Agent connections and role templates support global configuration only; ignored this source",
          },
        },
      ])
    if (!globalSource && result.agentConnections !== undefined) {
      warn("agentConnections")
      delete result.agentConnections
    }
    if (!globalSource && isRecord(result.collaboration) && result.collaboration.roleTemplates !== undefined) {
      warn("collaboration.roleTemplates")
      const collaboration = { ...result.collaboration }
      delete collaboration.roleTemplates
      result.collaboration = collaboration
    }
    return result
  }

  /** Unknown top-level keys: strip drops them silently, so report them as warnings (the file is not changed) */
  function emitUnknownTopLevelKeys(data: unknown, filePath: string) {
    if (!data || typeof data !== "object" || Array.isArray(data)) return
    const known = new Set(Object.keys(Info.shape))
    const unknown = Object.keys(data as Record<string, unknown>).filter((key) => !known.has(key))
    if (unknown.length === 0) return
    emitWarnings(
      unknown.map((key) => ({
        path: filePath,
        item: key,
        reason: `Unrecognized key: "${key}"`,
      })),
    )
  }

  /**
   * Resolves a plugin specifier from the config to an importable file:// URL. Returns undefined when it cannot be
   * resolved; the entry is then kept as is and plugin loading reports the error or installs it from npm.
   * - Absolute path or file:// URL: the file or directory package must exist
   * - Relative path: relative to the config file's directory
   * - Package name: an installed node_modules/<name>, searched upward from the config file's directory
   * import.meta.resolve(spec, parent) is not used: Node ignores parent by default and rejects Windows drive paths.
   */
  function resolvePluginSpec(spec: string, configFilepath: string) {
    if (spec.startsWith("file://")) return spec
    const base = path.dirname(configFilepath.startsWith("file://") ? fileURLToPath(configFilepath) : configFilepath)
    if (path.isAbsolute(spec)) return Npm.find(spec)
    if (/^.{1,2}[\/]/.test(spec)) return Npm.find(path.resolve(base, spec))
    const name = spec.startsWith("@") ? spec.split("@").slice(0, 2).join("@") : spec.split("@")[0]
    for (let dir = base; ; dir = path.dirname(dir)) {
      const found = Npm.find(path.join(dir, "node_modules", name))
      if (found) return found
      if (path.dirname(dir) === dir) return
    }
  }

  /** `only` limits which specifiers are resolved; without it all are resolved relative to the config file */
  function resolvePlugins(data: Info, configFilepath: string, only?: (spec: string) => boolean) {
    if (data.plugin) {
      for (let i = 0; i < data.plugin.length; i++) {
        const entry = data.plugin[i]!
        // For a `[name, options]` tuple only the specifier is resolved; options stay as is (opencode shape).
        const spec = pluginSpecifier(entry)
        if (only && !only(spec)) continue
        const resolved = resolvePluginSpec(spec, configFilepath)
        if (resolved) data.plugin[i] = typeof entry === "string" ? resolved : [resolved, entry[1]]
      }
    }
    return data
  }
