  // Managed settings directory for enterprise deployments (highest priority, admin-controlled)
  // These settings override all user and project settings
  function getManagedConfigDir(): string {
    switch (process.platform) {
      case "darwin":
        return "/Library/Application Support/merakcode"
      case "win32":
        return path.join(process.env.ProgramData || "C:\\ProgramData", "merakcode")
      default:
        return "/etc/merakcode"
    }
  }

  const managedConfigDir = process.env.MERAKCODE_TEST_MANAGED_CONFIG_DIR || getManagedConfigDir()

  function sanitizePath(input: string): string {
    return input.replace(/\0/g, "")
  }

  function mergeSources(target: Info, source: Info): Info {
    return Object.assign(
      mergeDeep(target, source),
      PluginSettings.merge(target, source),
      RuleSettings.merge(target, source),
    )
  }

