  export function projectMerakCodeFile(): string {
    // In a workspace, project-level settings go to the workspace data directory so the repositories stay clean.
    if (Instance.project.kind === "workspace") return workspaceMerakCodeFile()

    const dir = Instance.directory
    const dotDir = path.join(dir, ".merakcode")
    const dotJsonc = path.join(dotDir, "merakcode.jsonc")
    const dotJson = path.join(dotDir, "merakcode.json")
    if (existsSync(dotJsonc)) return dotJsonc
    if (existsSync(dotJson)) return dotJson
    const jsonc = path.join(dir, "merakcode.jsonc")
    const json = path.join(dir, "merakcode.json")
    if (existsSync(jsonc)) return jsonc
    if (existsSync(json)) return json
    return dotJson
  }

  /**
   * Merges a patch into the project merakcode.json(c) and refreshes the Instance config cache.
   * @param options.skipDispose only invalidate the config cache instead of disposing the Instance (hot updates)
   */
  export async function updateProjectMerakCode(partial: Info, options?: { skipDispose?: boolean }) {
    const filepath = projectMerakCodeFile()
    const next = await writeConfigWithRetry(filepath, partial)

    if (options?.skipDispose) {
      state.invalidate()
    } else {
      await reloadInstance()
    }
    void Bus.publish(UpdatedEvent, {})
    return next
  }

