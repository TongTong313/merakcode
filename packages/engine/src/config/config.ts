  // While a workflow is active, the full reload is deferred so that disposing after a config write does not abort
  // background workflows. Without active workflows the instance is disposed right away; otherwise the config is
  // invalidated (values are fresh immediately) and the dispose runs once all workflows have finished. Process exit
  // goes through the disposeAll shutdown path instead, where WorkflowState still aborts and persists workflows.
  async function reloadInstance() {
    if (!WorkflowState.hasActive()) {
      await Instance.dispose()
      return
    }
    state.invalidate()
    // The deferred callback runs outside the Instance AsyncLocalStorage context, so capture directory and re-provide.
    const directory = Instance.directory
    WorkflowState.requestReloadWhenIdle(() => void Instance.provide({ directory, fn: () => Instance.dispose() }))
  }

  async function reloadAll() {
    // Without an Instance context (e.g. /global PATCH) active workflows cannot be checked, so dispose everything.
    // Known limit: hasActive only sees the current instance; a workflow running in another project can still be
    // hit by disposeAll.
    if (!Instance.has() || !WorkflowState.hasActive()) {
      await Instance.disposeAll().catch(() => undefined)
      return
    }
    state.invalidateAll()
    WorkflowState.requestReloadWhenIdle(() => void Instance.disposeAll().catch(() => undefined))
  }

