  export type Warning = z.output<typeof Warning>

  export const Warning = z
    .object({
      path: z.string().describe("Path of the config file with the problem"),
      item: z.string().describe("Path of the config item, e.g. mcp.foo"),
      reason: z.string().describe("Human-readable reason"),
    })
    .meta({ ref: "ConfigWarning" })

  /** Degradation warnings collected while state() loads. Nothing is written to disk; the user fixes the file. */
  let activeWarnings: ConfigWarning[] | undefined

  /**
   * global() is a process-wide lazy. The desktop app often calls getGlobal() first, before any Instance or
   * activeWarnings exist, so unknown-key warnings written only to activeWarnings would be lost. This keeps the
   * warnings of the last global load for state() to merge.
   */
  let lastGlobalWarnings: ConfigWarning[] = []

  function emitWarnings(list: ConfigWarning[]) {
    for (const warning of list) {
      log.warn("config degraded, skipped invalid item", warning)
      activeWarnings?.push(warning)
    }
  }

  /** Parses JSON injected through a flag. On failure it is skipped with a warning so it cannot poison Config.state. */
  function parseFlagJson(text: string, flagName: string): unknown | undefined {
    try {
      return JSON.parse(text)
    } catch (err) {
      emitWarnings([
        {
          path: flagName,
          item: flagName,
          reason: {
            zh: `无效 JSON（${err instanceof Error ? err.message : String(err)}）；已临时跳过，请修正环境变量后重载`,
            en: `Invalid JSON (${err instanceof Error ? err.message : String(err)}); skipped for now. Fix the environment variable and reload.`,
          },
        },
      ])
      return
    }
  }

