const cell = (text = "") => text.replaceAll("|", "\\|").replaceAll("\n", " ")

const localized = z.strictObject({ zh: z.string().trim().min(1), en: z.string().trim().min(1) })
const schema = z.strictObject({
  domains: z.record(z.string().regex(/^[a-z]+$/), z.number().int().min(1).max(9)),
  codes: z.record(
    z.string().regex(/^[A-Z][A-Z0-9_]*$/),
    z.strictObject({
      code: z.string().regex(/^MRK-[1-9][0-9]{3}$/),
      domain: z.string(),
      status: z.number().int().min(400).max(599),
      retryable: z.boolean(),
      title: localized,
      hint: localized,
    }),
  ),
})

function parseCatalog(input: unknown) {
  const catalog = schema.parse(input)
  const seen = new Set<string>()
  for (const spec of Object.values(catalog.codes)) {
    if (seen.has(spec.code)) throw new Error(`Duplicate error code ${spec.code}`)
    seen.add(spec.code)
    if (catalog.domains[spec.domain] !== Number(spec.code[4])) throw new Error(`Invalid domain for ${spec.code}`)
  }
  return catalog
}

const sourceFile = path.resolve(import.meta.dirname, "..", "packages/util/errors.json")
const loadCatalog = () => parseCatalog(JSON.parse(readFileSync(sourceFile, "utf8")))

export async function buildCatalog(input: unknown) {
  const catalog = parseCatalog(input)
  const domain = Object.keys(catalog.domains)
    .map((name) => JSON.stringify(name))
    .join(" | ")
  const typescript = await format(
    `// Generated by pnpm generate:errors from packages/util/errors.json. Do not edit by hand.
export namespace ErrorCode {
  type Text = { zh: string; en: string }
  type Domain = ${domain}
  export type Spec = { code: \`MRK-\${number}\`; domain: Domain; status: number; retryable: boolean; title: Text; hint: Text }
  export const CATALOG = ${JSON.stringify(catalog.codes)} as const satisfies Record<string, Spec>
}`,
    { parser: "typescript", semi: false, printWidth: 120 },
  )
  const constants = Object.entries(catalog.codes)
    .map(([name, spec]) => {
      const identifier = name
        .toLowerCase()
        .split("_")
        .map((word) => word[0]!.toUpperCase() + word.slice(1))
        .join("")
      return `const ${identifier} = ${JSON.stringify(spec.code)}`
    })
    .join("\n\n")
  const go = `// Code generated by pnpm generate:errors from packages/util/errors.json. DO NOT EDIT.\npackage errorcode\n\n${constants}\n\nconst catalogJSON = ${JSON.stringify(JSON.stringify(catalog.codes))}\n`
  return { typescript, go }
}

export async function checkOutputs(files: { file: string; text: string }[]) {
  const stale: string[] = []
  for (const { file, text } of files) {
    const current = await readFile(file, "utf8").catch(() => "")
    if (current.replaceAll("\r\n", "\n") !== text) stale.push(file)
  }
  return stale
}

export function render(): string {
  const specs = Object.values(loadCatalog().codes).sort((a, b) => a.code.localeCompare(b.code))
  const sections = Object.keys(DOMAINS).flatMap((domain) => {
    const rows = specs.filter((spec) => spec.domain === domain)
    if (!rows.length) return []
    return [
      `## ${DOMAINS[domain]}`,
      "",
      "| 错误码 Code | 说明 | Meaning | 怎么办 · What to do |",
      "| --- | --- | --- | --- |",
      ...rows.map(
        (spec) =>
          `| ${spec.code} | ${cell(spec.title.zh)} | ${cell(spec.title.en)} | ${cell(spec.hint.zh)}<br>${cell(spec.hint.en)} |`,
      ),
      "",
    ]
  })
  return [INTRO, ...sections].join("\n")
}

async function main() {
  const root = path.resolve(import.meta.dirname, "..")
  const file = path.join(root, "docs", "errors.md")
  const config = await resolveConfig(file)
  const text = await format(render(), { ...config, filepath: file })
  const catalog = await buildCatalog(loadCatalog())
  const files = [
    { file, text },
    { file: path.join(root, "packages/util/src/error-code.ts"), text: catalog.typescript },
    { file: path.join(root, "merak/internal/platform/errorcode/catalog.gen.go"), text: catalog.go },
  ]
  if (process.argv.includes("--check")) {
    const stale = await checkOutputs(files)
    if (stale.length === 0) return
    console.error(`${stale.join(", ")} is out of date, run: pnpm generate:errors`)
    process.exitCode = 1
    return
  }
  for (const output of files) {
    await mkdir(path.dirname(output.file), { recursive: true })
    await writeFile(output.file, output.text)
  }
}

if (import.meta.main) await main()
