/**
 * Writes docs/errors.md from the error code catalog (packages/util/src/error-code.ts).
 * Usage (repo root): pnpm generate:errors, or pnpm check:errors to fail when the file is out of date.
 */
import path from "node:path"
import { format, resolveConfig } from "prettier"
import { ErrorCode } from "@merakcode/util/error-code"
import { Filesystem } from "@merakcode/util/filesystem"

const DOMAINS: Record<ErrorCode.Spec["domain"], string> = {
  engine: "1xxx 引擎与连接 · Engine and connection",
  provider: "2xxx 模型服务 · Model providers",
  config: "3xxx 配置 · Configuration",
  session: "4xxx 会话 · Sessions",
  tool: "5xxx 工具、权限与沙箱 · Tools, permissions and sandbox",
  extension: "6xxx 扩展（MCP、插件、技能）· Extensions (MCP, plugins, skills)",
  workspace: "7xxx 工作区与 Git · Workspace and git",
  update: "8xxx 安装与更新 · Install and update",
  internal: "9xxx 其他 · Other",
}

const INTRO = `# 错误码 · Error codes

> 这个文件由 \`pnpm generate:errors\` 根据 \`packages/util/src/error-code.ts\` 生成，不要手改。
> Generated by \`pnpm generate:errors\` from \`packages/util/src/error-code.ts\`. Do not edit by hand.

MerakCode 报错时会带一个错误码，比如 \`[MRK-2002]\`。在下面的表里搜这个码，就能看到是什么问题、该怎么办。

Every error MerakCode shows starts with a code such as \`[MRK-2002]\`. Search for it below to see what it means and
what to do.

## 遇到问题怎么办

1. 先看下表里对应错误码的建议。
2. 运行 \`merak doctor\`，它会检查安装、配置、模型服务和沙箱，并指出哪一项有问题。
3. 还是解决不了，运行 \`merak bug-report\`。它会把最近的日志和检查结果打成一个 zip（密钥等敏感信息会先去掉），
   在 GitHub 提 issue 时附上这个文件。
4. 想自己看日志：\`merak logs\` 会显示日志在哪，\`merak logs --tail\` 会实时打印最新的日志。

## When something goes wrong

1. Check the suggestion for your code in the table below.
2. Run \`merak doctor\`. It checks the install, configuration, model providers and sandbox, and points at what is wrong.
3. If that does not help, run \`merak bug-report\`. It zips recent logs and the doctor results (with keys and other
   secrets removed). Attach the file to a GitHub issue.
4. To read the logs yourself: \`merak logs\` shows where they are, and \`merak logs --tail\` follows the newest one.
`

const cell = (text = "") => text.replaceAll("|", "\\|").replaceAll("\n", " ")

export function render(): string {
  const specs = Object.values(ErrorCode.CATALOG as Record<string, ErrorCode.Spec>).sort((a, b) =>
    a.code.localeCompare(b.code),
  )
  const sections = (Object.keys(DOMAINS) as ErrorCode.Spec["domain"][]).flatMap((domain) => {
    const rows = specs.filter((spec) => spec.domain === domain)
    if (!rows.length) return []
    return [
      `## ${DOMAINS[domain]}`,
      "",
      "| 错误码 Code | 说明 | Meaning | 怎么办 · What to do |",
      "| --- | --- | --- | --- |",
      ...rows.map(
        (spec) =>
          `| ${spec.code} | ${cell(spec.title.zh)} | ${cell(spec.title.en)} | ${cell(spec.hint.zh)}<br>${cell(spec.hint.en)} |`,
      ),
      "",
    ]
  })
  return [INTRO, ...sections].join("\n")
}

async function main() {
  const file = path.resolve(import.meta.dirname, "..", "docs", "errors.md")
  const config = await resolveConfig(file)
  const text = await format(render(), { ...config, filepath: file })
  if (process.argv.includes("--check")) {
    const current = await Filesystem.readText(file).catch(() => "")
    if (current.replaceAll("\r\n", "\n") === text) return
    console.error("docs/errors.md is out of date, run: pnpm generate:errors")
    process.exitCode = 1
    return
  }
  await Filesystem.write(file, text)
}

if (import.meta.main) await main()
