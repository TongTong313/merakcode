import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const sql = (await readFile(new URL("schema/store.sql", root), "utf8")).replaceAll("\r\n", "\n")
const outputs = new Map([
  [
    "merak/internal/localstore/schema.gen.go",
    `// Code generated by script/generate-store.ts; DO NOT EDIT.\npackage localstore\n\nconst schema = \`${sql}\`\n`,
  ],
])
for (const [path, content] of outputs) {
  const target = new URL(path, root)
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== content) throw new Error(`Regenerate ${path}`)
  } else {
    await writeFile(fileURLToPath(target), content)
  }
}
